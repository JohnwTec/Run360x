export function getAgeCategoryFromAge(age?: number): AgeCategoryId {
  const safeAge = typeof age === 'number' && !Number.isNaN(age) ? age : 28;
  if (safeAge <= 20) return 'ate-20';
  if (safeAge <= 30) return '21-30';
  if (safeAge <= 40) return '31-40';
  if (safeAge <= 50) return '41-50';
  return '50-plus';
}

export function getAgeCategoryLabel(id: AgeCategoryId): string {
  return AGE_CATEGORIES.find((c) => c.id === id)?.label ?? '21 à 30 anos';
}

export function getGenderLabel(gender: AthleteGender): string {
  return gender === 'feminino' ? 'Feminino' : 'Masculino';
}

